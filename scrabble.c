#include <cs50.h>
#include <ctype.h>
#include <stdio.h>
#include <string.h>

// Points for each letter of the alphabet
int POINTS[] = {1, 3, 3, 2, 1, 4, 2, 4, 1, 8, 5, 1, 3, 1, 1, 3, 10, 1, 1, 1, 1, 4, 4, 8, 4, 10};

// Define Compute
int compute_score(string word);

int main(void)
{
    // Prompt users for two words
    string word1 = get_string("Player 1: ");
    string word2 = get_string("Player 2: ");

    // Add the values of each letter
    int score1 = compute_score(word1);
    int score2 = compute_score(word2);

    // Print the winner
    if (score1 > score2)
    {
        printf("Player 1 Wins!\n");
    }
    else if (score1 < score2)
    {
        printf("Player 2 Wins!\n");
    }
    else
    {
        printf("Tie!\n");
    }
}

int compute_score(string word)
{
    // Keep track of score
    int score = 0;

    // Calculate points per character
    // Ensure capital and lower case are counted the same
    for (int i = 0, len = strlen(word); i < len; i++)
    {
        if (isupper(word[i]))
        {
            score += POINTS[word[i] - 'A'];
        }
        else if (islower(word[i]))
        {
            score += POINTS[word[i] - 'a'];
        }
    }

    // Calculate the total score for word
    return score;
}
